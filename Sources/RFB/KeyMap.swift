        "\u{2C7}": 0xFE5A, "\u{B8}": 0xFE5B, "\u{2DB}": 0xFE5C,
    ]

    // keysym maps a key event: special keys by key code, everything else by
    // the character it types without modifiers. deadKey marks a keystroke
    // that only started a composition.
    public static func keysym(keyCode: UInt16, characters: String?, deadKey: Bool = false) -> UInt32? {
        if let keysym = special[keyCode] { return keysym }
        guard let scalar = characters?.unicodeScalars.first else { return nil }
        if deadKey, let dead = deadKeys[scalar] { return dead }
        return keysym(for: scalar)
    }

    public static func keysym(for scalar: Unicode.Scalar) -> UInt32? {
        switch scalar.value {
        case 0x0A, 0x0D: returnKey
        case 0x09: tab
        case 0x08, 0x7F: 0xFF08
        case 0x1B: 0xFF1B
        case 0x20...0x7E, 0xA0...0xFF: scalar.value
        case 0xF700...0xF8FF, 0..<0x20: nil
        default: 0x0100_0000 | scalar.value
        }
    }

    public static func scancode(keyCode: UInt16) -> UInt32? {
        scancodes[keyCode]
    }
}
