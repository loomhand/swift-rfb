    private static let deadKeys: [Unicode.Scalar: UInt32] = [
        "`": 0xFE50, "\u{B4}": 0xFE51, "^": 0xFE52, "~": 0xFE53, "\u{2DC}": 0xFE53, "\u{AF}": 0xFE54,
